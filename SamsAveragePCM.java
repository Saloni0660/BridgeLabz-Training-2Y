public class SamsAveragePCM {
    public static void main(String[] args) {
        // Given marks
        int maths = 94;
        int physics = 95;
        int chemistry = 96;

        // Average percentage across three subjects
        int average = (maths + physics + chemistry) / 3; // 285/3 = 95

        // Output (as specified)
        System.out.println("Sam's average mark in PCM is " + average);
    }
}
